"""Export outline data from the built OTFs for the specimen.

    .venv/bin/python scripts/specimen_data.py

Writes specimen/data.js: metrics, the design system, the supported codepoints
and every weight's cubic outlines with on/off-curve points.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import ufoLib2

sys.path.insert(0, str(Path(__file__).resolve().parent))

from fontTools.pens.recordingPen import DecomposingRecordingPen  # noqa: E402
from fontTools.pens.svgPathPen import SVGPathPen  # noqa: E402
from fontTools.ttLib import TTFont  # noqa: E402

from pfsans.system import ROOT, load  # noqa: E402


def export_face(stem: str) -> tuple[list[int], dict]:
    font = TTFont(ROOT / "fonts" / "otf" / f"{stem}.otf")
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    by_name = {}
    for cp, name in cmap.items():
        by_name.setdefault(name, []).append(cp)
    ufo = ufoLib2.Font.open(ROOT / "sources" / f"{stem}.ufo")
    notes = {g.name: g.lib.get("vn.ketviet.construction", "") for g in ufo}
    production = {v: k for k, v in ufo.lib.get("public.postscriptNames", {}).items()}
    glyphs = {}
    for name in font.getGlyphOrder():
        if name == ".notdef":
            continue
        rec = DecomposingRecordingPen(gs)
        gs[name].draw(rec)
        svg = SVGPathPen(gs)
        gs[name].draw(svg)
        points = []
        for op, args in rec.value:
            if op in ("moveTo", "lineTo"):
                points.append([round(args[0][0]), round(args[0][1]), 1])
            elif op == "curveTo":
                for i, p in enumerate(args):
                    points.append([round(p[0]), round(p[1]), 1 if i == 2 else 0])
        glyphs[name] = {
            "u": by_name.get(name, []),
            "w": font["hmtx"][name][0],
            "d": svg.getCommands(),
            "p": points,
        }
        note = notes.get(production.get(name, name), "")
        if note:
            glyphs[name]["note"] = note
    return sorted(cmap), glyphs


def main() -> None:
    system = load()
    faces, weights = {}, []
    codepoints = None
    for style in system.masters:
        weight = system.raw["masters"][style]["wght"]
        coverage, glyphs = export_face(f"{system.meta.postscriptFamily}-{style}")
        if codepoints is None:
            codepoints = coverage
        if coverage != codepoints:
            raise ValueError(f"Specimen glyph coverage differs at {style}")
        faces[weight] = glyphs
        weights.append({"weight": weight, "style": style})
    data = {
        "version": system.meta.version,
        "metrics": system.raw["metrics"],
        "identity": system.raw["identity"],
        "strokes": {m["wght"]: m["stroke"] for m in system.raw["masters"].values()},
        "codepoints": codepoints,
        "faces": faces,
        "weights": weights,
    }
    out = ROOT / "specimen" / "data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Generated by scripts/specimen_data.py from the built OTFs.\nwindow.PORTO_FAIFO_SANS = "
                   + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(faces)} weights, {out.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
